import type { AiFieldDef, AiToolDef } from '../ai.types.js';

/**
 * Danh mục model AI DeepCut hiện hành — đồng bộ từ GET https://aideepcut.com/api/workflows & /api/v1/workflows ngày 2026-11-14
 * (gồm 2 model Motion Control nền ảnh 10s / 20s, các sản phẩm ảnh/video chủ lực + 2 model âm thanh ElevenLabs).
 * Ô nhập giữ đúng `fieldName` của nguồn -> gửi thẳng làm `inputs`.
 * Giá mỗi lượt đọc trực tiếp ở GET /api/workflows (`costCredits`), mất kết nối thì dùng `fallbackCost`.
 */

const IMG = 'image/png,image/jpeg,image/webp';
const VID = 'video/mp4,video/quicktime,video/webm';
const AUDIO = 'audio/mpeg,audio/mp3,audio/wav,audio/x-wav,audio/mp4,audio/x-m4a';

export interface DeepcutModel extends Pick<AiToolDef, 'key' | 'name' | 'category' | 'icon' | 'description' | 'output' | 'pairs' | 'copies'> {
  /** Mã workflow phía nguồn */
  workflowId: string;
  /** Giá credit DeepCut khi không tải được bảng giá trực tiếp */
  fallbackCost: number;
  /** Giá credit DeepCut theo từng độ phân giải (khi nguồn tính giá theo resolution, vd Minimax H3-RH Enhanced) */
  resolutionCosts?: Record<string, number>;
  fields: AiFieldDef[];
}

/** Motion Control V2 (RunningHub, 720p 30fps): 2 ô `image` + `video`, khác nhau ở nhãn ô và thời lượng tối đa */
function motionV2(o: { key: string; workflowId: string; name: string; description: string; seconds: number; fallbackCost: number; keepVideoBg: boolean }): DeepcutModel {
  return {
    key: o.key,
    workflowId: o.workflowId,
    name: o.name,
    category: 'text',
    icon: 'person-standing',
    description: o.description,
    output: 'video',
    fallbackCost: o.fallbackCost,
    pairs: { fields: ['image', 'video'], max: 5, linkField: 'video' },
    copies: 4,
    fields: [
      {
        name: 'image',
        label: o.keepVideoBg ? 'Ảnh nhân vật thay thế' : 'Ảnh nhân vật & nền',
        type: 'image',
        required: true,
        accept: IMG,
        help: o.keepVideoBg ? 'Ảnh nhân vật muốn ghép vào video (JPG, PNG, WEBP)' : 'Ảnh nhân vật rõ mặt (JPG, PNG, WEBP) · giữ nguyên nền ảnh',
      },
      {
        name: 'video',
        label: o.keepVideoBg ? `Video gốc giữ nền (Tối đa ${o.seconds} giây)` : `Video chuyển động mẫu (Tối đa ${o.seconds} giây)`,
        type: 'video',
        required: true,
        accept: VID,
        help: o.keepVideoBg
          ? `Video gốc cần thay nhân vật (MP4, MOV, WEBM) · giữ nguyên bối cảnh, ánh sáng & âm thanh · tối đa ${o.seconds}s`
          : `Video hành động / nhảy múa mẫu (MP4, MOV, WEBM) · tối đa ${o.seconds}s`,
      },
    ],
  };
}

